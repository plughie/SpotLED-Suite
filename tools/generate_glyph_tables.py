#!/usr/bin/env python3
"""Generate Python, Android, and iOS glyph tables from glyph_data/spotled_glyphs.json."""

from __future__ import annotations

import argparse
import json
import pprint
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "glyph_data" / "spotled_glyphs.json"
GENERATED_HEADER = "// Generated by tools/generate_glyph_tables.py; edit glyph_data/spotled_glyphs.json.\n"
PYTHON_HEADER = "# Generated by tools/generate_glyph_tables.py; edit glyph_data/spotled_glyphs.json.\n"


def load_data() -> tuple[dict[str, list[str]], dict[str, str]]:
    data = json.loads(SOURCE.read_text())
    if data.get("format_version") != 1:
        raise ValueError("Unsupported glyph data format_version")
    compact = data["compact_3x5"]
    captured = data["captured_panel16_hex"]
    if not compact or "?" not in compact:
        raise ValueError("The compact font must include a fallback '?' glyph")
    if "73" not in captured:
        raise ValueError("The native glyph overrides must include the serifed capital I")
    for character, rows in compact.items():
        if len(character) != 1 or len(rows) != 5 or any(
                len(row) != 3 or set(row) - {"0", "1"} for row in rows):
            raise ValueError(f"Invalid 3x5 glyph data for {character!r}")
    for code, glyph in captured.items():
        if len(glyph) != 94 or any(char not in "0123456789abcdefABCDEF" for char in glyph):
            raise ValueError(f"Invalid native 16x16 FontObject for code point {code}")
    return compact, captured


def python_output(compact: dict[str, list[str]], captured: dict[str, str]) -> str:
    compact_literal = pprint.pformat(
        {key: tuple(rows) for key, rows in compact.items()}, sort_dicts=True, width=100
    )
    captured_literal = pprint.pformat(dict(sorted(captured.items(), key=lambda item: int(item[0]))),
                                      sort_dicts=False, width=100)
    return (
        PYTHON_HEADER
        + "COMPACT_FONT_3X5 = " + compact_literal + "\n\n"
        + "CAPTURED_PANEL16_HEX = " + captured_literal + "\n"
    )


def java_output(compact: dict[str, list[str]], captured: dict[str, str]) -> str:
    lines = [
        GENERATED_HEADER,
        "package com.spotled.app;\n",
        "import java.util.HashMap;\nimport java.util.Map;\n",
        "/** Generated compact and captured panel glyph data. */\n",
        "final class GeneratedGlyphs {\n",
        "    static final Map<Integer, String[]> COMPACT_3X5 = new HashMap<>();\n",
        "    static final Map<Integer, String> CAPTURED_PANEL16_HEX = new HashMap<>();\n",
        "    static {\n",
    ]
    for character, rows in compact.items():
        code = ord(character)
        row_values = ", ".join(json.dumps(row) for row in rows)
        lines.append(f"        COMPACT_3X5.put({code}, new String[] {{{row_values}}});\n")
    for code, glyph in sorted(captured.items(), key=lambda item: int(item[0])):
        lines.append(f"        CAPTURED_PANEL16_HEX.put({code}, {json.dumps(glyph)});\n")
    lines.extend([
        "    }\n\n",
        "    private GeneratedGlyphs() {}\n\n",
        "    static String[] compactRowsFor(int codePoint) {\n",
        "        int normalized = codePoint >= 0 && codePoint < 128\n",
        "                ? Character.toUpperCase((char) codePoint) : '?';\n",
        "        String[] rows = COMPACT_3X5.get(normalized);\n",
        "        return (rows == null ? COMPACT_3X5.get((int) '?') : rows).clone();\n",
        "    }\n\n",
        "    static byte[] capturedPanel16(int codePoint) {\n",
        "        String hex = CAPTURED_PANEL16_HEX.get(codePoint);\n",
        "        if (hex == null) return null;\n",
        "        byte[] result = new byte[hex.length() / 2];\n",
        "        for (int i = 0; i < result.length; i++)\n",
        "            result[i] = (byte) Integer.parseInt(hex.substring(i * 2, i * 2 + 2), 16);\n",
        "        return result;\n",
        "    }\n",
        "}\n",
    ])
    return "".join(lines)


def swift_output(compact: dict[str, list[str]], captured: dict[str, str]) -> str:
    lines = [
        GENERATED_HEADER,
        "enum GeneratedGlyphs {\n",
        "    static let compact3x5: [Character: [String]] = [\n",
    ]
    for character, rows in compact.items():
        lines.append(f"        {json.dumps(character)}: {json.dumps(rows)},\n")
    lines.extend([
        "    ]\n\n",
        "    static let capturedPanel16Hex: [Int: String] = [\n",
    ])
    for code, glyph in sorted(captured.items(), key=lambda item: int(item[0])):
        lines.append(f"        {code}: {json.dumps(glyph)},\n")
    lines.extend([
        "    ]\n\n",
        "    static func capturedPanel16(_ code: UInt8) -> [UInt8]? {\n",
        "        guard let hex = capturedPanel16Hex[Int(code)], hex.count.isMultiple(of: 2) else { return nil }\n",
        "        var bytes: [UInt8] = []\n",
        "        bytes.reserveCapacity(hex.count / 2)\n",
        "        var index = hex.startIndex\n",
        "        while index < hex.endIndex {\n",
        "            let next = hex.index(index, offsetBy: 2)\n",
        "            guard let byte = UInt8(hex[index..<next], radix: 16) else { return nil }\n",
        "            bytes.append(byte)\n",
        "            index = next\n",
        "        }\n",
        "        return bytes\n",
        "    }\n",
        "}\n",
    ])
    return "".join(lines)


def outputs(compact: dict[str, list[str]], captured: dict[str, str]) -> dict[Path, str]:
    return {
        ROOT / "spotled_common" / "generated_glyphs.py": python_output(compact, captured),
        ROOT / "android" / "app" / "src" / "main" / "java" / "com" / "spotled" / "app" / "GeneratedGlyphs.java": java_output(compact, captured),
        ROOT / "ios" / "SpotLEDCompanion" / "GeneratedGlyphs.swift": swift_output(compact, captured),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated platform files are stale")
    args = parser.parse_args()
    generated = outputs(*load_data())
    stale = [path for path, content in generated.items()
             if not path.exists() or path.read_text() != content]
    if args.check:
        if stale:
            print("Generated glyph tables are stale:", *(str(path.relative_to(ROOT)) for path in stale),
                  sep="\n  ", file=sys.stderr)
            return 1
        print("Generated glyph tables are current.")
        return 0
    for path, content in generated.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"Generated {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
